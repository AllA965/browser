download_progress = {}

class AgentRequest(BaseModel):
    task: str
    api_key: str
    base_url: str
    model: str

@app.post("/agent/stop")
async def stop_agent():
    """
    Stop all currently running agents.
    """
    print("Received stop request. Cancelling all running agents...")
    count = 0
    for task_id, task in list(running_agents.items()):
        if not task.done():
            task.cancel()
            count += 1
    return {"status": "success", "cancelled_count": count}

@app.post("/agent/run")
async def run_agent_endpoint(request: AgentRequest):
    """
    Wrapper to handle task management for the agent.
    """
    task_id = f"agent_{id(request)}_{asyncio.get_event_loop().time()}"
    loop = asyncio.get_running_loop()
    
    # Create the actual work task
    work_task = loop.create_task(do_run_agent(request))
    running_agents[task_id] = work_task
    
    try:
        result = await work_task
        return result
    except asyncio.CancelledError:
        print(f"Agent task {task_id} was cancelled.")
        return {
            "status": "cancelled",
            "result": "任务已被用户手动停止。",
            "is_successful": False
        }
    finally:
        # Clean up
        if task_id in running_agents:
            del running_agents[task_id]

async def do_run_agent(request: AgentRequest):
    """
    Run the browser-use agent with the provided task and LLM configuration.
    Connects to the local WebView2 instance via CDP (port 9222).
    """
    print(f"Received task: {request.task}")
    print(f"Model: {request.model}")
    print(f"Base URL: {request.base_url}")
    try:
        # 1. Initialize LLM
        # Handle cases where base_url might be empty or specific to a provider
        base_url = request.base_url if request.base_url else None
        
        # Determine which LLM provider to use
        if base_url and ("volces.com" in base_url or "volcengine" in base_url):
            llm = ChatVolcengine(
                api_key=request.api_key,
                base_url=base_url,
                model=request.model,
                temperature=0.0,
            )
        elif base_url and "deepseek" in base_url:
            llm = ChatDeepSeek(
                api_key=request.api_key,
                base_url=base_url,
                model=request.model,
                temperature=0.0,
            )
        else:
            llm = ChatOpenAI(
                api_key=request.api_key,
                base_url=base_url,
                model=request.model,
                temperature=0.0, # Agents work best with low temperature
            )

        # 2. Initialize Browser connecting to existing CDP
        browser = Browser(cdp_url="http://localhost:9222")

        # 3. Initialize Agent
        use_thinking = "flash" not in request.model.lower() and "thinking" not in request.model.lower()
        
        agent = Agent(
            task=request.task,
            llm=llm,
            browser=browser,
            directly_open_url=True, # Enable direct navigation to save steps
            use_thinking=use_thinking,
            max_actions_per_step=10, # Allow more actions per step to reduce overhead
        )

        # 4. Run Agent and return result
        history = await agent.run()
        
        # 5. Extract and Format result
        # Try multiple ways to get the final result text
        result_text = history.final_result()

        # If no explicit final_result, check for errors
        errors = history.errors()
        error_msg = ""
        if errors:
            error_msg = "\n".join([str(e) for e in errors if e is not None])
            print(f"Agent Errors: {error_msg}")
        
        # If no explicit final_result, look for extracted content in history
        if not result_text:
            contents = history.extracted_content()
            if contents:
                result_text = contents[-1]
                
        # If still nothing, check last model actions (maybe it just finished)
        if not result_text:
            actions = history.model_actions()
            if actions:
                # Look for a 'done' action or similar that might have text
                for action in reversed(actions):
                    if 'done' in str(action): # Check action as string since it might be a pydantic object
                        try:
                            # Try to get text if it's a dict or object
                            if isinstance(action, dict):
                                result_text = action.get('done', {}).get('text')
                            else:
                                result_text = getattr(action.done, 'text', None)
                        except:
                            pass
                        if result_text: break
        
        if not result_text:
            if error_msg:
                result_text = f"任务执行失败，错误信息: {error_msg}"
            else:
                result_text = "任务已执行完成，但未返回具体文本结果。请检查浏览器页面是否已达到预期状态。"

        base_success = history.is_successful()
        has_errors = bool(errors)
        is_successful = bool(base_success) and not has_errors

        return {
            "status": "success" if is_successful else "failed",
            "result": result_text,
            "steps": len(history.history),
            "is_successful": is_successful,
            "errors": errors
        }
    
    except Exception as e:
        import traceback
        traceback.print_exc()
        raise HTTPException(status_code=500, detail=str(e))

class VideoDownloadRequest(BaseModel):
    url: str
    save_path: Optional[str] = None
    format_id: Optional[str] = None
    # 新增字段支持直接数据模式
    direct_data: Optional[dict] = None
    # 新增字段支持 Cookie
    cookies: Optional[str] = None
    # 新增字段支持自定义 User-Agent
    user_agent: Optional[str] = None

@app.post("/video/info")
async def get_video_info(request: VideoDownloadRequest):
    """
    Get video info using yt-dlp from the provided URL, 
    or return direct data if provided.
    """
    # Debug print the request
    print(f"DEBUG: Request payload URL: {request.url}")
    
    # 如果提供了直接数据，跳过 yt-dlp 解析
    if request.direct_data:
        print(f"Received direct video data for: {request.direct_data.get('title')}")
        return {
            "status": "success",
            "title": request.direct_data.get('title'),
            "thumbnail": request.direct_data.get('cover'),
            "duration": request.direct_data.get('duration'),
            "formats": [
                {
                    "format_id": "direct",
                    "ext": "mp4",
                    "resolution": "original",
                    "note": "直接抓取的源地址",
                    "url": request.direct_data.get('url') # 内部使用
                }
            ]
        }

    cleaned_url = clean_video_url(request.url)
    print(f"Received video info request for URL: {request.url} -> Cleaned: {cleaned_url}")
    
    cookie_file = None
    try:
        ydl_opts = get_common_ydl_opts(cleaned_url, request.cookies, request.user_agent)
        cookie_file = ydl_opts.get('cookiefile')
        
        with yt_dlp.YoutubeDL(ydl_opts) as ydl:
            loop = asyncio.get_event_loop()
            try:
                info = await loop.run_in_executor(None, lambda: ydl.extract_info(cleaned_url, download=False))
                if info is None:
                    raise HTTPException(status_code=400, detail="解析失败：yt-dlp 未能获取视频信息。请确保页面已完全加载。")
            except yt_dlp.utils.DownloadError as de:
                # Provide a more user-friendly message for unsupported or invalid URLs
                error_msg = str(de)
                if "Unsupported URL" in error_msg:
                    raise HTTPException(status_code=400, detail="不支持的 URL。请提供具体的视频播放页面地址。")
                
                # 特殊提示抖音更新
                if "douyin.com" in cleaned_url:
                    raise HTTPException(status_code=400, detail=f"抖音视频解析失败，可能是反爬机制导致或链接失效。\n提示：尝试更新 yt-dlp 库或确保已登录网页端。")
                    
                raise HTTPException(status_code=400, detail=f"视频解析失败: {error_msg}")
            
            formats = []
            if 'formats' in info:
                for f in info['formats']:
                    # 只保留有视频和音频的格式，或者至少有视频的
                    if f.get('vcodec') != 'none':
                        formats.append({
                            'format_id': f.get('format_id'),
                            'ext': f.get('ext'),
                            'resolution': f.get('resolution') or f"{f.get('width')}x{f.get('height')}",
                            'filesize': f.get('filesize'),
                            'note': f.get('format_note') or f.get('format'),
                            'vcodec': f.get('vcodec'),
                            'acodec': f.get('acodec'),
                        })
            
            return {
                "status": "success",
                "title": info.get('title'),
                "thumbnail": info.get('thumbnail'),
                "duration": info.get('duration'),
                "formats": formats
            }
    except HTTPException:
        raise
    except Exception as e:
        import traceback
        traceback.print_exc()
        raise HTTPException(status_code=500, detail=f"服务器内部错误: {str(e)}")
    finally:
        # 清理临时文件
        if cookie_file and os.path.exists(cookie_file):
            try:
                os.remove(cookie_file)
                print(f"Cleaned up temporary cookie file: {cookie_file}")
            except:
                pass

@app.post("/video/download")
async def download_video(request: VideoDownloadRequest):
    """
    Download video using yt-dlp from the provided URL.
    Returns a task_id immediately and starts the download in the background.
    """
    if not request.save_path:
        raise HTTPException(status_code=400, detail="save_path is required for download")
    
    task_id = f"dl_{int(time.time())}_{id(request)}"
    download_progress[task_id] = {
        "status": "starting",
        "progress": 0,
        "filename": "video",
        "total_bytes": 0,
        "downloaded_bytes": 0,
        "speed": 0,
        "eta": 0
    }

    # 在后台启动下载
    asyncio.create_task(do_download_video(task_id, request))
    
    return {"status": "started", "task_id": task_id}

@app.get("/video/progress/{task_id}")
async def get_download_progress(task_id: str):
    """
    Get progress of a specific download task.
    """
    if task_id not in download_progress:
        raise HTTPException(status_code=404, detail="Task not found")
    return download_progress[task_id]

async def do_download_video(task_id: str, request: VideoDownloadRequest):
    """
    Background worker for video download.
    """
    try:
        # 如果提供了直接数据且选择了 direct 格式，直接下载 URL
        target_url = request.url
        if request.direct_data and request.format_id == "direct":
            target_url = request.direct_data.get("url")

        cleaned_url = clean_video_url(target_url)
        
        # 确保保存路径存在
        if not os.path.exists(request.save_path):
            os.makedirs(request.save_path)

        # 获取通用配置
        ydl_opts = get_common_ydl_opts(cleaned_url, request.cookies, request.user_agent)
        
        # 针对直接下载模式的特殊优化
        if request.format_id == "direct":
            ydl_opts['format'] = 'best'
        else:
            ydl_opts['format'] = request.format_id if request.format_id else 'best'
            
        def progress_hook(d):
            if d['status'] == 'downloading':
                # 计算进度百分比
                total = d.get('total_bytes') or d.get('total_bytes_estimate') or 0
                downloaded = d.get('downloaded_bytes') or 0
                percent = (downloaded / total * 100) if total > 0 else 0
                
                download_progress[task_id].update({
                    "status": "downloading",
                    "progress": round(percent, 1),
                    "filename": os.path.basename(d.get('filename', 'video')),
                    "total_bytes": total,
                    "downloaded_bytes": downloaded,
                    "speed": d.get('speed', 0),
                    "eta": d.get('eta', 0)
                })
            elif d['status'] == 'finished':
                download_progress[task_id].update({
                    "status": "completed",
                    "progress": 100,
                    "filename": os.path.basename(d.get('filename', 'video'))
                })

        ydl_opts.update({
            'outtmpl': os.path.join(request.save_path, '%(title)s.%(ext)s'),
            'progress_hooks': [progress_hook],
            'noprogress': True, # Disable console progress
        })

        # 如果有 direct_data，设置标题
        if request.direct_data:
            title = request.direct_data.get('title', 'video')
            safe_title = "".join([c for c in title if c.isalnum() or c in (' ', '.', '_', '-')]).rstrip()
            ydl_opts['outtmpl'] = os.path.join(request.save_path, f'{safe_title}.%(ext)s')

        # 运行下载 (在线程池中执行以避免阻塞事件循环)
        loop = asyncio.get_event_loop()
        await loop.run_in_executor(None, lambda: yt_dlp.YoutubeDL(ydl_opts).download([cleaned_url]))

    except Exception as e:
        import traceback
        traceback.print_exc()
        download_progress[task_id].update({
            "status": "failed",
            "error": str(e)
        })

