def clean_video_url(url: str) -> str:
    """
    Clean and normalize URLs for better extraction.
    """
    # 处理抖音链接
    if "douyin.com" in url:
        # 处理包含 modal_id 的精选/推荐等页面，直接归一到视频详情页
        modal_match = re.search(r'modal_id=([^&/?]+)', url)
        if modal_match:
            modal_id = modal_match.group(1)
            if modal_id:
                return f"https://www.douyin.com/video/{modal_id}"
        # 如果是短链接 v.douyin.com，保持原样让 yt-dlp 处理重定向
        if "v.douyin.com" in url:
            return url
        # 如果是普通链接，移除多余的查询参数，只保留视频 ID 相关的
        if "/video/" in url:
            video_id_match = re.search(r'video/(\d+)', url)
            if video_id_match:
                return f"https://www.douyin.com/video/{video_id_match.group(1)}"
    return url

import tempfile

import time

def create_cookie_file(cookies_str: str):
    """
    将 Cookie 字符串转换为 yt-dlp 兼容的 Netscape 格式临时文件。
    """
    if not cookies_str:
        return None
    
    try:
        fd, path = tempfile.mkstemp(suffix='.txt', prefix='cookies_')
        with os.fdopen(fd, 'w', encoding='utf-8') as f:
            f.write("# Netscape HTTP Cookie File\n")
            f.write("# This file is generated by Browser-Use Bridge\n\n")
            
            # 设置一个较长的过期时间 (1年)
            expiry = int(time.time()) + 31536000
            
            # 抖音的 Cookie 往往包含多个域，Netscape 格式对 domain 校验非常严格
            # 强制为 .douyin.com 和 www.douyin.com 写入
            domains = [".douyin.com", "www.douyin.com", ".amemv.com"]
            
            for item in cookies_str.split(';'):
                if '=' in item:
                    parts = item.strip().split('=', 1)
                    if len(parts) == 2:
                        name, value = parts
                        for d in domains:
                            # 格式: domain, initial_dot, path, secure, expiration, name, value
                            # initial_dot: 如果 domain 以 . 开头则为 TRUE
                            dot_flag = "TRUE" if d.startswith(".") else "FALSE"
                            f.write(f"{d}\t{dot_flag}\t/\tFALSE\t{expiry}\t{name}\t{value}\n")
        return path
    except Exception as e:
        print(f"Error creating cookie file: {e}")
        return None

